import { chromium } from "@playwright/test";
const out = process.argv[2] ?? "./test-results/admin";
const base = "http://127.0.0.1:8000/admin";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto(`${base}/login`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/admin-login.png` });
await page.fill("input[name=username]", "admin@dortech-demo.ru");
await page.fill("input[name=password]", "Dortech2026!");
await page.click("button[type=submit]");
await page.waitForLoadState("networkidle");
console.log("after login:", page.url());
await page.screenshot({ path: `${out}/admin-home.png`, fullPage: true });
await page.goto(`${base}/equipment/list`, { waitUntil: "networkidle" });
console.log("equipment list title:", await page.title());
await page.screenshot({ path: `${out}/admin-equipment-list.png`, fullPage: false });
await page.goto(`${base}/equipment/edit?pk=1`, { waitUntil: "networkidle" });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/admin-equipment-edit.png`, fullPage: true });
await page.goto(`${base}/equipment-image/create`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/admin-image-create.png`, fullPage: true });
await page.goto(`${base}/inquiry/list`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/admin-inquiries.png`, fullPage: false });
await page.goto(`${base}/inquiry/detail?pk=18`, { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/admin-inquiry-detail.png`, fullPage: true });
await page.goto(`${base}/page/edit?pk=1`, { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/admin-page-edit.png`, fullPage: true });
console.log("tinymce present:", await page.locator(".tox-tinymce").count());
await browser.close();
